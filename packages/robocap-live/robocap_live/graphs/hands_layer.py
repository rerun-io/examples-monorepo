"""The hands-layer graph (SPEC 5.3, lossless): one catalog segment's luma framesets through the ``hands`` node into the sinks.

Its picture and guide: ``GRAPH.md`` (generated by tests/test_app.py) and the "pipeline (debug)" tab of every run.
"""

import re
from collections.abc import Mapping
from pathlib import Path
from typing import cast

from dagkit.graph import AsOf, Block, Graph
from dagkit.node import Node, Source
from dagkit.sinks import LayerFileSink, segment_layers
from dagkit.sources import Column, IterSource, RecordingSource, SegmentRef
from simplecv.sources.catalog_video import CatalogLumaSource
from slam_rs.types import CatalogPoses

from robocap_live.nodes.hands import HandsNode
from robocap_live.types import RIG_ROOT, CapRig

CAMERAS: tuple[str, ...] = tuple(f"rig_00/cam_{i:02d}" for i in range(6))  # under /world, in the core's index order
GROUP_TOLERANCE_NS: int = 3_000_000  # a frameset holds each camera's next frame within 3 ms of its opening, as live


def segment_source(segment: SegmentRef, group_tolerance_ns: int = GROUP_TOLERANCE_NS, catalog_poses: bool = True) -> CatalogLumaSource:
    """The segment's raw luma framesets, base-layer rig and (``catalog_poses``) whole ``slam_rs`` pose table (an older ``slam``
    layer writes that entity too)."""
    if (
        segment.timeline != "video_time"
        or not re.fullmatch(r"robocap__\w+__s\d+", segment.segment)
        or (catalog_poses and "slam_rs" not in segment_layers(segment))
    ):
        raise ValueError(f"{segment.segment} on {segment.timeline}: needs a robocap__<device>__s<session> id on video_time with a slam_rs layer")
    statics: dict[str, Column] = {"cap_rig": Column(CapRig, RIG_ROOT, static=True)} | (
        {"poses": Column(CatalogPoses, RIG_ROOT)} if catalog_poses else {}
    )
    return CatalogLumaSource(segment, CAMERAS, group_tolerance_ns=group_tolerance_ns, statics=statics)


class PosesCheckpoint(IterSource):
    """Read the poses the VIO graph published.

    Its ``slam_rs`` layer file (``publish.published``, read when this graph starts) as the STATIC pose table, f32 as stored."""

    def __init__(self, publish: LayerFileSink, timeline: str = "video_time") -> None:
        columns: dict[str, Column] = {"poses": Column(CatalogPoses, RIG_ROOT)}
        super().__init__({"poses": CatalogPoses}, lambda: RecordingSource(cast(Path, publish.published), columns, timeline).events(), clock=timeline)


def hands_layer_graph(source: Source, hands: HandsNode, sinks: Mapping[str, Node], poses: Source | None = None) -> Graph:
    """``poses``: the source of the STATIC pose table when the segment source does not carry it (the VIO graph's layer)."""
    graph = Graph(
        "robocap-hands-layer",
        about="One robocap catalog segment's camera framesets through robocap-live's Rust hand "
        "pipeline into the segment's `hands` layer: a file the publish step moves into place and registers when asked.",
    )
    segment = graph.source("segment", source)
    node = graph.node("hands", hands)
    graph.edge(segment["frames"], node["frames"], Block(4))
    graph.edge(segment["cap_rig"], node["cap_rig"], AsOf())
    graph.edge((segment if poses is None else graph.source("slam", poses))["poses"], node["poses"], AsOf())
    graph.sinks({port: node[port] for port in hands.outputs}, sinks)
    return graph
